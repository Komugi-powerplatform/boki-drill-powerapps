"""問題データの原本。実行すると data/questions.json を生成する。

書式: Q(id, category, text, debit, credit, explain, method=None, traps=())
  debit / credit は [(科目, 金額) | (科目, 金額, [別解科目...])]
  traps はよくある誤記（不正解として扱う表記の例。解説で見せる）
範囲: 全経3級 令和9年度改定（全経の標準勘定科目表・出題範囲表に準拠。問題文は独自に作成）
"""

import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data/questions.json"
QS = []


def Q(id, category, text, debit, credit, explain, method=None, traps=()):
    def lines(xs):
        out = []
        for x in xs:
            d = {"account": x[0], "amount": x[1]}
            if len(x) > 2:
                d["alts"] = list(x[2])
            out.append(d)
        return out

    QS.append(
        {
            "id": id,
            "category": category,
            "method": method,
            "text": text,
            "debit": lines(debit),
            "credit": lines(credit),
            "explain": explain,
            "traps": list(traps),
        }
    )


